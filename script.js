// Состояние приложения
const state = {
    currentChapter: 0,
    readChapters: new Set(),
    nightMode: false
};

// Инициализация приложения
function initApp() {
    renderChaptersList();
    renderChapterContent();
    setupEventListeners();
    updateProgress();
}

// Рендер списка глав
function renderChaptersList() {
    const listElement = document.getElementById('chapterList');
    listElement.innerHTML = '';

    chapters.forEach((chapter, index) => {
        const li = document.createElement('li');
        li.className = `chapter-item ${state.currentChapter === index ? 'active' : ''}`;
        li.dataset.chapterId = index;
        
        li.innerHTML = `
            <span>Глава ${index + 1}: ${chapter.title}</span>
            <span class="progress-dot ${state.readChapters.has(index) ? 'read' : ''}"></span>
        `;
        
        listElement.appendChild(li);
    });
}

// Рендер содержимого главы
function renderChapterContent() {
    const chapter = chapters[state.currentChapter];
    document.getElementById('chapterTitle').textContent = `Глава ${state.currentChapter + 1}: ${chapter.title}`;
    
    const versesContainer = document.getElementById('versesContainer');
    versesContainer.innerHTML = '';
    
    chapter.verses.forEach(verse => {
        const verseElement = document.createElement('div');
        verseElement.className = 'verse';
        
        // Проверяем, начинается ли строка с номера стиха
        if (/^\d+/.test(verse)) {
            const verseNumber = verse.match(/^\d+/)[0];
            const verseText = verse.replace(/^\d+\.?\s*/, '');
            verseElement.innerHTML = `<span class="verse-number">${verseNumber}.</span> ${verseText}`;
        } else {
            verseElement.innerHTML = `<strong>${verse}</strong>`;
        }
        
        versesContainer.appendChild(verseElement);
    });
    
    // Добавляем текущую главу в прочитанные
    state.readChapters.add(state.currentChapter);
    updateProgress();
}

// Обновление прогресса чтения
function updateProgress() {
    const progress = (state.readChapters.size / chapters.length) * 100;
    document.getElementById('progressFill').style.width = `${progress}%`;
    document.getElementById('progressText').textContent = `${Math.round(progress)}%`;
    
    // Обновляем точки прогресса в списке глав
    document.querySelectorAll('.progress-dot').forEach((dot, index) => {
        dot.classList.toggle('read', state.readChapters.has(index));
    });
}

// Настройка обработчиков событий
function setupEventListeners() {
    // Переключение глав
    document.getElementById('chapterList').addEventListener('click', e => {
        const chapterItem = e.target.closest('.chapter-item');
        if (chapterItem) {
            state.currentChapter = parseInt(chapterItem.dataset.chapterId);
            renderChaptersList();
            renderChapterContent();
        }
    });
    
    // Ночной режим
    document.getElementById('themeToggle').addEventListener('click', () => {
        state.nightMode = !state.nightMode;
        document.body.classList.toggle('night-mode', state.nightMode);
        document.getElementById('themeToggle').textContent = 
            state.nightMode ? 'Дневной режим' : 'Ночной режим';
    });
}

// Запуск приложения при загрузке
document.addEventListener('DOMContentLoaded', initApp);